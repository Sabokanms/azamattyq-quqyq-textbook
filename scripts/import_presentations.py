"""Export the course slides with desktop PowerPoint (Windows, pywin32, Pillow)."""

import json
import posixpath
import re
from pathlib import Path
from tempfile import TemporaryDirectory
from xml.etree import ElementTree as ET
from zipfile import ZipFile

import win32com.client
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "презентации"
OUTPUT = ROOT / "assets" / "presentations"
REL_ID = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"


def slide_descriptions(source):
    """Read slide text in the order specified by the PowerPoint presentation."""
    with ZipFile(source) as archive:
        presentation = ET.fromstring(archive.read("ppt/presentation.xml"))
        relationships = ET.fromstring(archive.read("ppt/_rels/presentation.xml.rels"))
        targets = {rel.get("Id"): rel.get("Target") for rel in relationships}
        descriptions = []
        for entry in presentation.findall("{*}sldIdLst/{*}sldId"):
            target = targets[entry.get(REL_ID)]
            part = posixpath.normpath(posixpath.join("ppt", target)).lstrip("/")
            slide = ET.fromstring(archive.read(part))
            paragraphs = [
                "".join(run.text or "" for run in paragraph.iterfind(".//{*}t")).strip()
                for paragraph in slide.iterfind(".//{*}p")
            ]
            descriptions.append("\n".join(line for line in paragraphs if line))
        return descriptions


def export_deck(powerpoint, source, destination, temp):
    descriptions = slide_descriptions(source)
    deck = powerpoint.Presentations.Open(str(source), ReadOnly=True, WithWindow=False)
    try:
        count = deck.Slides.Count
        if count != len(descriptions) or count == 0:
            raise ValueError(f"Unexpected slide count in {source.name}")
        height = 1080
        width = round(height * deck.PageSetup.SlideWidth / deck.PageSetup.SlideHeight)
        thumb_width = 192
        thumb_height = round(thumb_width * height / width)
        thumbnails = Image.new("RGB", (thumb_width, thumb_height * count))
        destination.mkdir(parents=True, exist_ok=True)
        for index, slide in enumerate(deck.Slides, start=1):
            png = temp / f"slide-{index}.png"
            slide.Export(str(png), "PNG", width, height)
            with Image.open(png) as image:
                image.save(destination / f"{index}.webp", quality=88, method=4)
                thumbnail = image.resize((thumb_width, thumb_height), Image.Resampling.LANCZOS)
                thumbnails.paste(thumbnail, (0, (index - 1) * thumb_height))
            png.unlink()
        # A single small image supplies the entire thumbnail pane for this topic.
        thumbnails.save(destination / "thumbnails.webp", quality=84, method=4)
        return {"file": source.name, "width": width, "height": height, "slides": descriptions}
    finally:
        deck.Close()


def render_presentations(sources, staging):
    metadata = {}
    powerpoint = win32com.client.DispatchEx("PowerPoint.Application")
    security = powerpoint.AutomationSecurity
    try:
        powerpoint.AutomationSecurity = 3  # msoAutomationSecurityForceDisable
        with TemporaryDirectory() as temp:
            for number, source in sorted(sources.items()):
                metadata[number] = export_deck(powerpoint, source, staging / str(number), Path(temp))
                print(f"Topic {number}: {len(metadata[number]['slides'])} slides", flush=True)
    finally:
        powerpoint.AutomationSecurity = security
        if powerpoint.Presentations.Count == 0:
            powerpoint.Quit()

    manifest = "// Generated by scripts/import_presentations.py\nwindow.coursePresentations = "
    manifest += json.dumps(metadata, ensure_ascii=False, indent=2) + ";\n"
    (staging / "decks.js").write_text(manifest, encoding="utf-8")


def main():
    sources = {}
    for source in SOURCE.iterdir():
        match = re.match(r"^(\d+)\.", source.name)
        if match and source.suffix.lower() in {".pptx", ".pptm"}:
            number = int(match[1])
            if number in sources:
                raise ValueError(f"Two presentations for topic {number}")
            sources[number] = source
    if not sources:
        raise FileNotFoundError(f"No numbered presentations in {SOURCE}")

    # Finish every Office export before publishing the images and finally the manifest.
    with TemporaryDirectory(dir=OUTPUT.parent) as temp:
        staging = Path(temp)
        render_presentations(sources, staging)
        for number in sources:
            destination = OUTPUT / str(number)
            destination.mkdir(parents=True, exist_ok=True)
            for image in (staging / str(number)).iterdir():
                image.replace(destination / image.name)
        (staging / "decks.js").replace(OUTPUT / "decks.js")


if __name__ == "__main__":
    main()
